import pandas as pd
import matplotlib.pyplot as plt
data = {
   "produit":["ordinateur", "téléphone", "casque", "ordinateur", "casque"],
   "prix":[1200, 800, 100, 1200, 100],
   "quantité":[2, 3, 5, 1, 4]
}
df = pd.DataFrame(data)
df["chiffre_affaires"] = df["prix"] * df["quantité"]

print(df)
print("chiffre d'affaires total:", df["chiffre_affaires"].sum())
print("Ventes par produit:")
print(df.groupby("produit")["chiffre_affaires"].sum())